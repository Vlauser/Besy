/**
 * Единая физика движения.
 *
 * До этого каждый экран анимировался по-своему: где-то пружина, где-то
 * линейный переход, где-то ничего. Глаз это замечает раньше, чем цвета:
 * вещи ведут себя непоследовательно, и приложение кажется собранным из
 * кусков. Один набор кривых и длительностей на всё — и оно становится
 * цельным, даже если ничего больше не менять.
 */

/** Появление и уход: быстро наружу, мягко внутрь. */
export const EASE = "cubic-bezier(0.22, 1, 0.36, 1)";
/** Возврат на место — с лёгким перелётом, как у предмета. */
export const SPRING = "cubic-bezier(0.18, 0.89, 0.32, 1.28)";
/** Улёт за экран — с разгоном. */
export const THROW = "cubic-bezier(0.32, 0, 0.67, 0)";

export const DURATION = {
  /** Отклик на касание: быстрее — и человек не свяжет действие с ответом. */
  tap: 140,
  /** Смена экрана и появление элементов. */
  screen: 260,
  /** Шторки и попапы: им нужно чуть больше, они крупнее. */
  sheet: 300,
};

export const transition = (property = "all", ms = DURATION.tap, curve = EASE) =>
  `${property} ${ms}ms ${curve}`;
