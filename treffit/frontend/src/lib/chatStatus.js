/**
 * Подпись под именем собеседника в шапке чата.
 *
 *  Вынесена из разметки ради одной вещи: её легко проверить. Правило тут
 *  тонкое и уже один раз было нарушено — сервер отдаёт `revealed: true`,
 *  когда слепой режим выключен, потому что фотографии в ответе и правда
 *  открыты. Но это внутренний признак, а не новость для человека: в
 *  выключенном режиме их никто и не закрывал, и «фото открыто» в шапке
 *  выглядело как сообщение о событии, которого не было.
 */
export function partnerStatus({ typing, blindMode, revealed, remaining, online }) {
  if (typing) return { text: "печатает…", tone: "typing" };
  if (blindMode) {
    return revealed
      ? { text: "фото открыто", tone: "precious" }
      : { text: `ещё ${remaining} сообщ. до фото`, tone: "muted" };
  }
  return { text: online ? "онлайн" : "не в сети", tone: "muted" };
}
