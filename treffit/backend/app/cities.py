# Порядок показа: сначала города с афишей, дальше по убыванию величины.
NAMES: tuple[str, ...] = tuple(name for name, _, _ in CITIES)

# По каким городам тянем события. Остальные источник не отдаёт.
SYNC_SLUGS: tuple[str, ...] = tuple(slug for _, slug, _ in CITIES if slug)

_BY_SLUG = {slug: name for name, slug, _ in CITIES if slug}


def _key(text: str) -> str:
    """Строка в виде, пригодном для сравнения: без регистра, ё=е, дефис=пробел."""
    cleaned = text.strip().lower().replace("ё", "е").replace("-", " ")
    return " ".join(cleaned.split())


_LOOKUP: dict[str, str] = {}
for _name, _slug, _aliases in CITIES:
    _LOOKUP.setdefault(_key(_name), _name)
    if _slug:
        _LOOKUP.setdefault(_key(_slug), _name)
    for _alias in _aliases:
        _LOOKUP.setdefault(_key(_alias), _name)


def name_for_slug(slug: str) -> str:
    """Каноничное название по слагу источника; незнакомый слаг — как есть."""
    return _BY_SLUG.get(slug, slug)


# Название города — это буквы, пробелы и дефисы. Цифры и знаки — не город.
_LOOKS_LIKE_A_CITY = re.compile(r"^[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z\s\-']{1,63}$")


def normalize(text: str | None) -> str | None:
    """Написанное человеком → каноничное название, либо None для мусора.

    Известный город приводим к единому виду: «мск», «Москва » и «москва»
    обязаны стать одной «Москвой», иначе подбор и афиша, ищущие точным
    совпадением, окажутся пустыми — и ни одной ошибки при этом не возникнет.

    Незнакомый город принимаем как есть, прибрав лишние пробелы и подняв
    первую букву. Отказывать человеку из-за того, что мы не дописали
    справочник, нельзя: город нужен ему прежде всего для знакомств.
    """
    if not text:
        return None
    known = _LOOKUP.get(_key(text))
    if known:
        return known

    cleaned = " ".join(text.strip().split())
    if not _LOOKS_LIKE_A_CITY.match(cleaned):
        return None
    # «каменск-уральский» → «Каменск-Уральский», не ломая «Улан-Удэ».
    return "-".join(part[:1].upper() + part[1:] for part in cleaned.split("-"))
